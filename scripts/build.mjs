import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const read = p => readFile(path.join(root, p), 'utf8');
const content = '// Generated by npm run build. Edit src/ instead.\n(function () {\n' +
  (await read('src/protocol.cjs')).replaceAll('Object.hasOwn(', 'Object.prototype.hasOwnProperty.call(') + '\n' +
  await read('src/engine.js') + '\n' + await read('src/main.js') + '\n})();\n';
// Older Figma JS runtimes need hasOwnProperty.call rather than Object.hasOwn.
if (process.argv.includes('--check')) {
  if (await read('plugin/code.js') !== content || await read('plugin/ui.html') !== await read('src/ui.html')) {
    throw new Error('Fichiers générés obsolètes : npm run build');
  }
  console.log('Plugin généré à jour.');
} else {
  await mkdir(path.join(root, 'plugin'), { recursive: true });
  await writeFile(path.join(root, 'plugin/code.js'), content);
  await writeFile(path.join(root, 'plugin/ui.html'), await read('src/ui.html'));
  console.log('Plugin prêt : plugin/manifest.json');
}
